class AppSkinBackground extends StatelessWidget {
  const AppSkinBackground({
    super.key,
    required this.child,
    this.color,
    this.skin,
    this.liftForNav = true,
    this.scaleByWidth = false,
    this.animate = false,
  });

  static const transitionDuration = Duration(milliseconds: 420);

  final Widget child;
  final Color? color;
  final AppSkin? skin;
  final bool liftForNav;
  final bool scaleByWidth;
  final bool animate;

  @override
  Widget build(BuildContext context) {
    final preference = AppScope.of(context).themePreference;
    return ListenableBuilder(
      listenable: preference,
      builder: (context, _) {
        final colors = AppColors.of(context);
        final dark = Theme.of(context).brightness == Brightness.dark;
        final skin = this.skin ?? preference.skin;
        final fill = AppSkinAssets.fillColor(
          skin,
          dark,
          color ?? colors.background,
        );
        final decorations = switch (skin) {
          AppSkin.classic => null,
          AppSkin.blossom => _BlossomDecorations(
              liftForNav: liftForNav,
              scaleByWidth: scaleByWidth,
            ),
          AppSkin.summerBeach => _SummerBeachDecorations(
              liftForNav: liftForNav,
              scaleByWidth: scaleByWidth,
            ),
          AppSkin.autumnForest => _AutumnForestDecorations(
              liftForNav: liftForNav,
              scaleByWidth: scaleByWidth,
            ),
          AppSkin.snowyWinter => _SnowyWinterDecorations(
              liftForNav: liftForNav,
              scaleByWidth: scaleByWidth,
            ),
          AppSkin.squishyBear => _SquishyBearDecorations(
              liftForNav: liftForNav,
              scaleByWidth: scaleByWidth,
            ),
          AppSkin.strawberryMilk => _StrawberryMilkDecorations(
              liftForNav: liftForNav,
              scaleByWidth: scaleByWidth,
            ),
          AppSkin.onionVillage => _OnionVillageDecorations(
              liftForNav: liftForNav,
              scaleByWidth: scaleByWidth,
            ),
          AppSkin.lovelyBear => _LovelyBearDecorations(
              liftForNav: liftForNav,
              scaleByWidth: scaleByWidth,
            ),
          AppSkin.rainyDay => _RainyDayDecorations(
              liftForNav: liftForNav,
              scaleByWidth: scaleByWidth,
            ),
        };
        return Stack(
          fit: StackFit.expand,
          children: [
            if (animate)
              AnimatedContainer(
                duration: transitionDuration,
                curve: Curves.easeInOut,
                color: fill,
              )
            else
              ColoredBox(color: fill),
            if (animate)
              AnimatedSwitcher(
                duration: transitionDuration,
                switchInCurve: Curves.easeInOut,
                switchOutCurve: Curves.easeInOut,
                child: KeyedSubtree(
                  key: ValueKey(skin),
                  child: decorations ?? const SizedBox.expand(),
                ),
              )
            else if (decorations != null)
              decorations,
            child,
          ],
        );
      },
    );
  }
}

class _BlossomDecorations extends StatelessWidget {
  const _BlossomDecorations({
    required this.liftForNav,
    this.scaleByWidth = false,
  });

  final bool liftForNav;
  final bool scaleByWidth;

  @override
  Widget build(BuildContext context) {
    final dark = Theme.of(context).brightness == Brightness.dark;
    return LayoutBuilder(
      builder: (context, constraints) {
        final width = constraints.maxWidth;
        final height = constraints.maxHeight;
        final span = scaleByWidth
            ? width
            : constraints.biggest.shortestSide;
        final paddingBottom = MediaQuery.paddingOf(context).bottom;
        final petalBottom = liftForNav ? 66 + paddingBottom : height * 0.04;
        final petal90 = dark
            ? AppSkinAssets.petal90Dark
            : AppSkinAssets.petal90Light;
        final petal180 = dark
            ? AppSkinAssets.petal180Dark
            : AppSkinAssets.petal180Light;
        final petal270 = dark
            ? AppSkinAssets.petal270Dark
            : AppSkinAssets.petal270Light;
        final hills = dark
            ? AppSkinAssets.hillsDark
            : AppSkinAssets.hillsLight;
        final hillsHeight =
            (width * 600 / 2000).clamp(0.0, height * 0.32);

        Widget petal(String asset) {
          return Image.asset(
            asset,
            fit: BoxFit.contain,
            filterQuality: FilterQuality.medium,
          );
        }

        return IgnorePointer(
          child: Stack(
            children: [
              Positioned(
                left: 0,
                right: 0,
                bottom: 0,
                height: hillsHeight,
                child: Image.asset(
                  hills,
                  fit: BoxFit.cover,
                  alignment: Alignment.bottomCenter,
                  filterQuality: FilterQuality.medium,
                ),
              ),
              Positioned(
                top: span * 0.02,
                right: span * 0.02,
                width: span * 0.26,
                child: petal(petal90),
              ),
              Positioned(
                top: span * 0.04,
                left: span * 0.22,
                width: span * 0.14,
                child: petal(petal270),
              ),
              Positioned(
                top: span * 0.16,
                left: span * 0.02,
                width: span * 0.2,
                child: petal(petal180),
              ),
              Positioned(
                top: height * 0.28,
                right: span * 0.08,
                width: span * 0.16,
                child: petal(petal270),
              ),
              Positioned(
                left: width * 0.5 - span * 0.1,
                top: height * 0.38,
                width: span * 0.2,
                child: petal(petal180),
              ),
              Positioned(
                left: width * 0.58,
                top: height * 0.52,
                width: span * 0.14,
                child: petal(petal90),
              ),
              Positioned(
                left: span * 0.06,
                bottom: petalBottom,
                width: span * 0.22,
                child: petal(petal270),
              ),
              Positioned(
                right: span * 0.04,
                bottom: petalBottom + span * 0.08,
                width: span * 0.18,
                child: petal(petal90),
              ),
            ],
          ),
        );
      },
    );
  }
}

